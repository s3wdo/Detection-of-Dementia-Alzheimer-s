/// Explainability for one analysis. Until the model provides maps this states
/// plainly that none is available; doctors also see the technical details.
class ExplainabilityScreen extends ConsumerWidget {
  const ExplainabilityScreen({super.key, required this.analysisId, required this.forPatient});

  final String analysisId;
  final bool forPatient;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final args = (analysisId: analysisId, patientView: forPatient);
    final analysis = ref.watch(analysisProvider(args));
    final image = ref.watch(analysisImageProvider(analysisId)).value;
    final explanation = ref.watch(analysisExplanationProvider(analysisId)).value;
    final a = analysis.value;
    final patientName = a == null || forPatient ? null : ref.watch(patientProvider(a.patientId)).value?.fullName;

    return Scaffold(
      appBar: AppBar(
        title: PageTitle(
          'Explainability',
          subtitle: a == null ? null : [if (patientName != null) patientName, Fmt.date(a.createdAt)].join(' · '),
        ),
      ),
      body: AsyncValueView<AnalysisSummary>(
        value: analysis,
        onRetry: () => ref.invalidate(analysisProvider(args)),
        data: (a) => ListView(
          padding: const EdgeInsets.fromLTRB(AppSpacing.screen, 0, AppSpacing.screen, AppSpacing.xxl),
          children: [
            ExplainabilityPanel(
              image: explanation?.image ?? (forPatient ? null : image),
              heatmap: explanation?.heatmap,
              height: 300,
              showOpacity: true,
            ),
            const SizedBox(height: AppSpacing.xl),
            const Divider(),
            const SizedBox(height: AppSpacing.xl),
            Text(forPatient ? 'What the map shows' : 'How to read the map', style: AppTextStyles.headline),
            const SizedBox(height: AppSpacing.sm),
            Text(
              forPatient
                  ? 'Red and yellow areas show where the computer model looked most when it made its suggestion. '
                      'They are not a diagnosis and do not show where disease or damage is.'
                  : 'Before analysis the server keeps only the brain (masking, as in the training data). '
                      "Red and yellow regions raised the model's score for its predicted class most (Grad-CAM, "
                      'last convolutional block). They show what the model relied on, not proven lesions, and carry '
                      'no anatomical claim.',
              style: AppTextStyles.bodySmall,
            ),
            if (!forPatient) ...[
              const SizedBox(height: AppSpacing.lg),
              Row(children: [
                Expanded(
                  child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    const Text('Predicted class', style: AppTextStyles.caption),
                    Text(a.predicted.label, style: AppTextStyles.label.copyWith(fontSize: 16)),
                  ]),
                ),
                const SizedBox(width: AppSpacing.md),
                Expanded(
                  child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    const Text('Model confidence', style: AppTextStyles.caption),
                    Text(Fmt.percent(a.confidence), style: AppTextStyles.mono.copyWith(fontSize: 16)),
                  ]),
                ),
              ]),
              const SizedBox(height: AppSpacing.xl),
              TechPanel(
                title: 'Technical details · clinicians only',
                locked: true,
                rows: [
                  ('Target class', a.predicted.label),
                  ('Model', '${a.modelName} · ${a.modelVersion}'),
                  ('Explainability method', explanation == null ? 'None for this result' : 'Grad-CAM, last convolutional block'),
                  ('Status', explanation == null ? 'Not generated' : 'Generated by the server'),
                ],
              ),
            ] else ...[
              const SizedBox(height: AppSpacing.lg),
              const InfoNote('Ask your doctor if you have questions about your result.'),
            ],
          ],
        ),
      ),
    );
  }
}
